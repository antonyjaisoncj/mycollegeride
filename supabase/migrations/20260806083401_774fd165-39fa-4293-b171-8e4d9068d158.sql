-- Payments
CREATE TYPE public.penalty_stage AS ENUM ('on_time', 'fine', 'superfine', 'blacklisted');
CREATE TYPE public.payment_mode AS ENUM ('cash', 'upi', 'bank');

CREATE TABLE public.payments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  student_id uuid NOT NULL REFERENCES public.students(id) ON DELETE CASCADE,
  period date NOT NULL,
  base_amount numeric(10,2) NOT NULL,
  penalty_amount numeric(10,2) NOT NULL DEFAULT 0,
  total_amount numeric(10,2) NOT NULL,
  stage public.penalty_stage NOT NULL,
  mode public.payment_mode NOT NULL,
  reference text,
  receipt_no text NOT NULL UNIQUE,
  paid_at timestamptz NOT NULL DEFAULT now(),
  recorded_by uuid REFERENCES auth.users(id) ON DELETE SET NULL,
  UNIQUE (student_id, period)
);

GRANT SELECT, INSERT, UPDATE, DELETE ON public.payments TO authenticated;
GRANT ALL ON public.payments TO service_role;
ALTER TABLE public.payments ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Students read own payments"
  ON public.payments FOR SELECT TO authenticated
  USING (EXISTS (
    SELECT 1 FROM public.students s
    WHERE s.id = payments.student_id AND s.user_id = auth.uid()
  ));

CREATE POLICY "Admins manage payments"
  ON public.payments FOR ALL TO authenticated
  USING (public.has_role(auth.uid(), 'admin'))
  WITH CHECK (public.has_role(auth.uid(), 'admin'));

